def generate_test_script(
    name: str,
    feature: str,
    test_type: str = "ui",
    language: str = "python",
    **kwargs
) -> GeneratedCode:
    """
    Standalone function to generate test scripts.
    
    Args:
        name: Test name
        feature: Feature being tested
        test_type: Type of test
        language: Programming language
        **kwargs: Additional parameters
        
    Returns:
        Generated code
    """
    lang = Language(language.lower())
    generator = CodeGenerator(language=lang)
    return generator.generate(name, feature, test_type, **kwargs)


